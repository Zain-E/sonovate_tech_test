select
    company_number,
    -- The last segment of the PSC's self link is its id.
    regexp_extract(links ->> 'self', '[^/]+$') as psc_id,
    kind as psc_kind,
    name as psc_name,
    name_elements ->> 'title' as name_title,
    name_elements ->> 'forename' as forename,
    name_elements ->> 'middle_name' as middle_name,
    name_elements ->> 'surname' as surname,
    nationality,
    country_of_residence,
    cast(date_of_birth ->> 'year' as integer) as birth_year,
    cast(date_of_birth ->> 'month' as integer) as birth_month,
    from_json(natures_of_control, '["VARCHAR"]') as natures_of_control,
    cast(notified_on as date) as notified_on,
    cast(ceased_on as date) as ceased_on,
    coalesce(ceased, ceased_on is not null) as is_ceased,
    coalesce(is_sanctioned, false) as is_sanctioned,
    identification ->> 'legal_form' as legal_form,
    identification ->> 'legal_authority' as legal_authority,
    identification ->> 'registration_number' as registration_number,
    identification ->> 'place_registered' as place_registered,
    identification ->> 'country_registered' as country_registered,
    address ->> 'premises' as address_premises,
    address ->> 'address_line_1' as address_line_1,
    address ->> 'address_line_2' as address_line_2,
    address ->> 'locality' as address_locality,
    address ->> 'region' as address_region,
    address ->> 'postal_code' as address_postal_code,
    address ->> 'country' as address_country
from {{ source('companies_house', 'persons_with_significant_control') }}
